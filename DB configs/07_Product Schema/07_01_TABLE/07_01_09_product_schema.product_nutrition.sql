  CREATE TABLE product_schema.product_nutrition (
      id UUID PRIMARY KEY DEFAULT uuidv7(),
      product_id UUID UNIQUE NOT NULL REFERENCES product_schema.products(id) ON DELETE CASCADE,
      serving_size DECIMAL(10,2) NOT NULL,
      serving_unit VARCHAR(20) NOT NULL,
      servings_per_container DECIMAL(10,2),
      calories DECIMAL(10,2),
      protein DECIMAL(10,2),
      carbohydrates DECIMAL(10,2),
      fat DECIMAL(10,2),
      saturated_fat DECIMAL(10,2),
      trans_fat DECIMAL(10,2),
      cholesterol DECIMAL(10,2),
      sodium DECIMAL(10,2),
      fiber DECIMAL(10,2),
      sugar DECIMAL(10,2),
      added_sugar DECIMAL(10,2),
      vitamin_a DECIMAL(10,2),
      vitamin_c DECIMAL(10,2),
      vitamin_d DECIMAL(10,2),
      vitamin_e DECIMAL(10,2),
      vitamin_k DECIMAL(10,2),
      vitamin_b1 DECIMAL(10,2),
      vitamin_b2 DECIMAL(10,2),
      vitamin_b3 DECIMAL(10,2),
      vitamin_b6 DECIMAL(10,2),
      vitamin_b12 DECIMAL(10,2),
      calcium DECIMAL(10,2),
      iron DECIMAL(10,2),
      potassium DECIMAL(10,2),
      magnesium DECIMAL(10,2),
      zinc DECIMAL(10,2),
      other_nutrients JSONB,
      allergens TEXT[],
      dietary_info TEXT[],
      created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
  );

  CREATE INDEX idx_product_nutrition_product_id ON product_schema.product_nutrition(product_id);